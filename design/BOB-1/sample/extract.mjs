// Reads Helix's board (Backlog.md files) and writes the sample the prototype draws from.
// Read only: it never writes to the source repo.
//   node design/BOB-1/sample/extract.mjs <key> <repo> <feature>
//   helix ~/Code/helix-navigator-picard LAND-49, and bobnet . BOB-1 (this repo's own board)
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { execFileSync } from "node:child_process";
import { homedir } from "node:os";
import { fileURLToPath } from "node:url";

const [key = "helix", repoArg = join(homedir(), "Code/helix-navigator-picard"), featureId = "LAND-49"] = process.argv.slice(2);
const repo = repoArg.replace(/^~/, homedir());
const root = join(repo, "product/backlog");
const out = join(dirname(fileURLToPath(import.meta.url)), `${key}.js`);

function front(text) {
  const m = text.match(/^---\n([\s\S]*?)\n---/);
  const f = {};
  if (!m) return f;
  const lines = m[1].split("\n");
  for (let i = 0; i < lines.length; i++) {
    const kv = lines[i].match(/^([a-z_]+):\s?(.*)$/);
    if (!kv) continue;
    let [, k, v] = kv;
    if (v === ">-" || v === "|" || v === "") {
      const parts = [];
      while (i + 1 < lines.length && /^\s/.test(lines[i + 1])) parts.push(lines[++i].trim());
      v = k === "title" || v ? parts.join(" ") : parts.map((p) => p.replace(/^- /, ""));
    }
    if (v === "[]") v = [];
    if (typeof v === "string") v = v.replace(/^'(.*)'$/, "$1").replace(/''/g, "'");
    f[k] = v;
  }
  return f;
}
function ac(text) {
  const s = text.match(/<!-- AC:BEGIN -->([\s\S]*?)<!-- AC:END -->/);
  if (!s) return [0, 0];
  const all = s[1].match(/^- \[[ x]\] #/gm) ?? [];
  return [all.filter((l) => l.includes("[x]")).length, all.length];
}
function read(dir) {
  return readdirSync(join(root, dir)).filter((n) => n.endsWith(".md")).map((n) => {
    const text = readFileSync(join(root, dir, n), "utf8");
    const f = front(text);
    const [done, total] = ac(text);
    return { ...f, dir, file: `product/backlog/${dir}/${n}`, ac: [done, total] };
  });
}
const num = (id) => id.replace(/^[A-Z]+-/, "").split(".").map(Number);
const byId = (a, b) => { const x = num(a.id), y = num(b.id); for (let i = 0; i < Math.max(x.length, y.length); i++) { const d = (x[i] ?? -1) - (y[i] ?? -1); if (d) return d; } return 0; };

const tasks = [...read("tasks"), ...read("completed")];
const drafts = read("drafts");
const milestones = read("milestones");
const at = execFileSync("git", ["-C", repo, "log", "-1", "--format=%h %cI"], { encoding: "utf8" }).trim().split(" ");

const features = tasks.filter((t) => t.type === "increment" && !t.parent_task_id);
const kids = (id) => tasks.filter((t) => t.parent_task_id === id).sort(byId);
const releases = milestones.sort((a, b) => a.id.localeCompare(b.id)).map((m) => {
  const fs = features.filter((f) => f.milestone === m.id)
    .sort((a, b) => (a.ordinal ? +a.ordinal : Infinity) - (b.ordinal ? +b.ordinal : Infinity) || byId(a, b));
  return {
    id: m.id, title: m.title,
    features: fs.map((f) => {
      const k = kids(f.id);
      const acs = k.reduce((s, t) => [s[0] + t.ac[0], s[1] + t.ac[1]], f.ac);
      return { id: f.id, title: f.title, status: f.status, ordinal: f.ordinal ?? null, tasks: k.length,
        tasksDone: k.filter((t) => t.status === "Done").length, ac: acs };
    }),
  };
});
const open = (t) => t.status !== "Done";
const today = new Date(at[1]);
const age = (d) => Math.floor((today - new Date(`${d.replace(" ", "T")}Z`)) / 864e5); // Backlog.md dates are UTC
const sample = {
  source: { repo: repoArg, commit: at[0], committed: at[1], dir: "product/backlog",
    config: "backlog.config.yml" },
  counts: {
    tasks: tasks.length, drafts: drafts.length, features: features.length, releases: milestones.length,
    byStatus: Object.fromEntries(["Draft", "Ready", "In Progress", "In Review", "Done"].map((s) => [s, tasks.filter((t) => t.status === s).length])),
    openBugs: [...tasks, ...drafts].filter((t) => t.type === "bug" && open(t)).length,
  },
  releases,
  noRelease: features.filter((f) => !f.milestone).sort(byId).map((f) => ({ id: f.id, title: f.title, status: f.status })),
  feature: featureId,
  tasks: kids(featureId).map((t) => ({ id: t.id, title: t.title, status: t.status, type: t.type, ac: t.ac,
    assignee: t.assignee ?? [] })),
  drafts: drafts.sort(byId).map((d) => ({ id: d.id, title: d.title, type: d.type ?? null, created: d.created_date,
    age: age(d.created_date), milestone: d.milestone ?? null })),
};
writeFileSync(out, `// Generated by extract.mjs from ${repoArg} at ${at[0]}. Do not edit.\n(window.SAMPLES ??= {})[${JSON.stringify(key)}] = ${JSON.stringify(sample, null, 1)};\n`);
console.log(`wrote ${out}: ${sample.counts.tasks} tasks, ${sample.counts.drafts} drafts, ${sample.tasks.length} ${featureId} tasks`);
